#!/usr/bin/env python3
"""把基准 JSON 渲染成双语文档（docs/en/benchmarks.md 与 docs/zh/benchmarks.md）。

**文档由生成器产出，不手抄数字。** 手抄的数字一定会过期，而过期的数字比没有数字更糟。
唯一的例外是「方法说明」部分——那是人写的解释，生成器只负责把它和表格拼起来。

用法：
    scripts/bench-render.py --input bench/baseline-default.json
"""

from __future__ import annotations

import argparse
import json
from typing import Any

WORKLOAD_ZH = {
    "point-lookup": "点查（主键 = 常量）",
    "range-scan": "范围扫描",
    "write": "写入（组提交）",
    "count-star": "COUNT(*)",
    "full-scan": "全表扫描（对照）",
    "storage": "存储足迹",
}
WORKLOAD_EN = {
    "point-lookup": "Point lookup (PK = const)",
    "range-scan": "Range scan",
    "write": "Write (group commit)",
    "count-star": "COUNT(*)",
    "full-scan": "Full scan (baseline)",
    "storage": "Storage footprint",
}
CACHE_ZH = {
    "miss": "未命中",
    "hit": "命中",
    "single-writer": "单写者",
    "baseline": "对照",
    "on-disk": "落盘",
}
CACHE_EN = {
    "miss": "cold",
    "hit": "warm",
    "single-writer": "single writer",
    "baseline": "baseline",
    "on-disk": "on disk",
}


def cache_label(cache: str, zh: bool) -> str:
    table = CACHE_ZH if zh else CACHE_EN
    if cache in table:
        return table[cache]
    if cache.startswith("concurrent-"):
        n = cache.removeprefix("concurrent-")
        return f"并发 {n}" if zh else f"concurrent {n}"
    return cache


def unit_label(unit: str, zh: bool) -> str:
    m = ({"op": "每次操作", "row": "每行", "txn": "每事务", "query": "每次查询"} if zh
         else {"op": "per op", "row": "per row", "txn": "per txn", "query": "per query"})
    return m.get(unit, unit)


def fmt(v: float, digits: int = 2) -> str:
    if v == 0:
        return "0"
    if abs(v) >= 1000:
        return f"{v:,.0f}"
    return f"{v:.{digits}f}"


def render(report: dict[str, Any], zh: bool) -> str:
    ds = report["dataset"]
    L = (lambda en, cn: cn if zh else en)
    out: list[str] = []
    if zh:
        out += [
            "# 基准结果",
            "",
            "> 本页由 `scripts/bench-render.py` 从基准 JSON 生成，**请勿手工编辑数字**。",
            "",
            f"- 版本：`{report['version']}`（`{report['commit']}`）",
            f"- 档位：`{report['profile']}` · 后端：`{report['backend']}`",
            f"- 数据集：{ds['rows']:,} 行，种子 {ds['seed']}，块大小 {ds['blockBytes'] // 1024} KiB，"
            f"每行 {ds['rowBytes']} 字节",
            f"- 生成时间：{report['startedAt']}",
            "",
            "## 怎么看这张表",
            "",
            "**先看请求数，再看延迟。** 这个项目的成本与延迟都由对象存储请求驱动：",
            "请求数是确定性的（同样的代码 + 同样的数据集必然同样的请求数），可以作为门禁；",
            "延迟依赖机器，换台笔记本就差一倍，只能作为参考。",
            "",
            "**缓存命中与未命中分两栏。** 命中一栏好看是因为数据已经在内存里，不代表对象存储便宜。",
            "对外说性能时，未命中一栏才是真话。",
            "",
            "## 结果",
            "",
            "| 负载 | 缓存 | 请求/单位 | 字节/单位 | p50 | p95 | p99 | 吞吐 |",
            "|---|---|---:|---:|---:|---:|---:|---:|",
        ]
    else:
        out += [
            "# Benchmark results",
            "",
            "> Generated by `scripts/bench-render.py` from the benchmark JSON. **Never hand-edit numbers.**",
            "",
            f"- Version: `{report['version']}` (`{report['commit']}`)",
            f"- Profile: `{report['profile']}` · backend: `{report['backend']}`",
            f"- Dataset: {ds['rows']:,} rows, seed {ds['seed']}, block size {ds['blockBytes'] // 1024} KiB, "
            f"{ds['rowBytes']} bytes/row",
            f"- Generated at: {report['startedAt']}",
            "",
            "## How to read this",
            "",
            "**Requests first, latency second.** Cost and latency in this project are both driven by object-store",
            "requests. Request counts are deterministic (same code + same dataset ⇒ same count) and can gate a PR;",
            "latency depends on the machine and is advisory only.",
            "",
            "**Cold and warm are separate columns.** Warm numbers look great because the data is already in memory;",
            "the cold column is what the object store actually costs you.",
            "",
            "## Results",
            "",
            "| Workload | Cache | Requests/unit | Bytes/unit | p50 | p95 | p99 | Throughput |",
            "|---|---|---:|---:|---:|---:|---:|---:|",
        ]

    names = WORKLOAD_ZH if zh else WORKLOAD_EN
    for m in report["metrics"]:
        name = names.get(m["workload"], m["workload"])
        if m["workload"] == "storage":
            continue
        lat = m["latencyUs"]
        thr = m["throughputPerSec"]
        thr_s = f"{fmt(thr)} {m['unit']}/s" if thr > 0 else "—"
        out.append(
            f"| {name} | {cache_label(m['cache'], zh)} | {fmt(m['requestsPerOp'], 3)} "
            f"{unit_label(m['unit'], zh)} | {fmt(m['bytesPerOp'])} B | "
            f"{lat['p50']:,} µs | {lat['p95']:,} µs | {lat['p99']:,} µs | {thr_s} |"
        )

    storage = [m for m in report["metrics"] if m["workload"] == "storage"]
    if storage:
        s = storage[0]["extra"]
        out += ["", "## " + L("Storage footprint", "存储足迹"), ""]
        out.append(
            L(
                f"- data blocks (`.dat`): **{fmt(s['dataBytes'] / 1024 / 1024)} MiB**"
                f" ({fmt(s['dataBytesPerRow'])} B/row)\n"
                f"- index objects (`.idx`): **{fmt(s['indexBytes'] / 1024 / 1024)} MiB**"
                f" ({fmt(s['indexRatio'] * 100)}% of data, resident in memory)\n"
                f"- total: **{fmt(s['bytesPerRow'])} B/row**",
                f"- 数据块（`.dat`）：**{fmt(s['dataBytes'] / 1024 / 1024)} MiB**（{fmt(s['dataBytesPerRow'])} 字节/行）\n"
                f"- 索引对象（`.idx`）：**{fmt(s['indexBytes'] / 1024 / 1024)} MiB**"
                f"（数据的 {fmt(s['indexRatio'] * 100)}%，常驻内存）\n"
                f"- 合计：**{fmt(s['bytesPerRow'])} 字节/行**",
            )
        )

    out += ["", "## " + L("Reproduce", "如何复现")]
    out += [
        "",
        "```bash",
        "./gradlew :yb-bench:benchPublic \\",
        f"  -PYB_BENCH_PROFILE={report['profile']} -PYB_BENCH_OUT=bench/current.json",
        "scripts/bench-compare.py --baseline bench/baseline-<profile>.json \\",
        "                         --current bench/current.json",
        "```",
        "",
        L(
            "Point the harness at a real bucket with `-PYB_S3_ENDPOINT` / `YB_S3_ACCESS_KEY` / "
            "`YB_S3_SECRET_KEY`; the default is an in-process S3-compatible server, which keeps the numbers "
            "about YangBase itself rather than about network jitter.",
            "用 `-PYB_S3_ENDPOINT` / `YB_S3_ACCESS_KEY` / `YB_S3_SECRET_KEY` 可以打真实桶；"
            "默认用进程内的 S3 兼容服务器，这样测的是 YangBase 本身而不是网络抖动。",
        ),
        "",
        "## " + L("What gates a pull request", "PR 门禁管什么"),
        "",
        L(
            "- **Hard failure:** `requestsPerOp` / `bytesPerOp` / storage footprint regress by more than 5%."
            " These are deterministic, so a failure there is a real regression.\n"
            "- **Exception — concurrent writes:** batch sizes depend on thread scheduling, so the ratio moves"
            " between machines without any code change (first CI run: 0.188 → 0.212 with identical code)."
            " It is gated by an *invariant* instead: averaged requests per transaction must stay ≤ 1.\n"
            "- **Warning only:** p50/p95/p99 latency regresses by more than 5% (with a 200 µs noise floor)."
            " Shared CI runners cannot support a hard latency gate; pretending otherwise just gets the gate disabled.\n"
            "- **Excluded:** anything that needs a real cloud backend (OSS/COS/OBS/R2/B2 latency profile)."
            " Those numbers live in the conformance reports, not here.",
            "- **硬失败**：`requestsPerOp` / `bytesPerOp` / 存储足迹回退超过 5%。"
            "这些是确定性指标，回退就是真回退。\n"
            "- **例外 —— 并发写入**：组提交的批次大小取决于线程调度，代码没变也会在机器之间飘"
            "（第一次 CI 就撞到 0.188 → 0.212）。所以它改用**不变式**门禁：平均每事务请求数必须 ≤ 1。\n"
            "- **仅告警**：p50/p95/p99 延迟回退超过 5%（下限 200 µs 噪声地板）。"
            "共享 CI 机器撑不起延迟硬门禁，硬做只会让人把门禁关掉。\n"
            "- **不在此页**：需要真实云后端的数字（OSS/COS/OBS/R2/B2 的延迟画像）。"
            "那些在 conformance 报告里，不在这里。",
        ),
        "",
    ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True)
    ap.add_argument("--out-en", default="docs/en/benchmarks.md")
    ap.add_argument("--out-zh", default="docs/zh/benchmarks.md")
    args = ap.parse_args()
    with open(args.input, encoding="utf-8") as f:
        report = json.load(f)
    with open(args.out_en, "w", encoding="utf-8") as f:
        f.write(render(report, zh=False) + "\n")
    with open(args.out_zh, "w", encoding="utf-8") as f:
        f.write(render(report, zh=True) + "\n")
    print(f"已生成 {args.out_en} 与 {args.out_zh}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
